export function getStream(id: StreamId): Stream {
  // Streams are a fixed literal union, so a miss means a corrupt persisted value.
  return streams.find((s) => s.id === id) ?? streams[0]!;
}

export function getSubject(id: string): Subject | undefined {
  return subjectIndex.get(id);
}

/** Subjects for a stream, already ordered by descending coefficient. */
export function subjectsForStream(id: StreamId): Array<Subject & { coefficient: number }> {
  return getStream(id)
    .subjects.map((entry) => {
      const subject = subjectIndex.get(entry.subjectId);
      return subject ? { ...subject, coefficient: entry.coefficient } : null;
    })
    .filter((s): s is Subject & { coefficient: number } => s !== null)
    .sort((a, b) => b.coefficient - a.coefficient);
}

export function countLessons(subject: Subject): number {
  return subject.units.reduce((total, unit) => total + unit.lessons.length, 0);
}

let lessonIndex: Map<string, { lesson: Lesson; unit: Unit; subject: Subject }> | null = null;

function buildLessonIndex() {
  const index = new Map<string, { lesson: Lesson; unit: Unit; subject: Subject }>();
  for (const subject of subjects) {
    for (const unit of subject.units) {
      for (const lesson of unit.lessons) {
        index.set(lesson.id, { lesson, unit, subject });
      }
    }
  }
  return index;
}

export function findLesson(id: string) {
  lessonIndex ??= buildLessonIndex();
  return lessonIndex.get(id);
}

export function allLessons() {
  lessonIndex ??= buildLessonIndex();
  return [...lessonIndex.values()];
}
