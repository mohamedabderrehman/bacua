/**
 * Algerian BAC curriculum.
 *
 * Shape: Stream → (Subject, coefficient) → Unit → Lesson.
 *
 * Subjects live in a flat catalogue keyed by id and streams reference them, because a
 * subject like الرياضيات appears in all six streams with a different coefficient each
 * time. Duplicating the lesson tree per stream would be the obvious wrong move.
 *
 * This is seed content shaped like what a real content pipeline would emit — replacing
 * it with imported files is a data swap, not a refactor.
 */

export type StreamId = 'sci' | 'math' | 'tech' | 'eco' | 'lit' | 'lang';

export type SubjectIconKey =
  | 'sigma'
  | 'atom'
  | 'dna'
  | 'book'
  | 'brain'
  | 'globe'
  | 'languages'
  | 'moon'
  | 'calculator'
  | 'trending'
  | 'scale'
  | 'cpu';

export interface Lesson {
  id: string;
  title: string;
  /** One-line description shown in list rows and used for search. */
  summary: string;
  objectives: string[];
  /** Lightweight markdown — the same renderer the chat uses. */
  body: string;
  formulas?: string[];
}

export interface Unit {
  id: string;
  title: string;
  lessons: Lesson[];
}

export interface Subject {
  id: string;
  name: string;
  /** Two or three characters for the card glyph fallback. */
  short: string;
  icon: SubjectIconKey;
  /** Per-subject accent so the grid is scannable at a glance. */
  hue: string;
  units: Unit[];
}

export interface StreamSubject {
  subjectId: string;
  coefficient: number;
}

export interface Stream {
  id: StreamId;
  name: string;
  short: string;
  subjects: StreamSubject[];
}

